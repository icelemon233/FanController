import { type ThemeConfig, theme } from 'antd';
import type { ThemeMode } from './runtime.ts';

const fontFamily = '"Segoe UI Variable Text", "Segoe UI", "Microsoft YaHei UI", sans-serif';

export function createAppTheme(mode: ThemeMode, reducedMotion = false) {
  const dark = mode === 'dark';
  const palette = dark
    ? {
        accent: '#bdeaf7',
        ground: '#1b1d20',
        sidebar: '#16181b',
        surface: '#24272b',
        elevated: '#24272b',
        ink: '#f2efea',
        muted: '#b8b2aa',
        border: '#3b4147',
        controlBorder: '#7b838c',
        selected: '#263c45',
        primary: '#a8dff1',
        onPrimary: '#20343d',
        success: '#addca5',
        successBg: '#253327',
        warning: '#f4d48a',
        warningBg: '#392f1c',
        danger: '#f6a6b6',
        dangerBg: '#3c2730',
      }
    : {
        accent: '#27677e',
        ground: '#fffcf6',
        sidebar: '#f4f4f0',
        surface: '#ffffff',
        elevated: '#ffffff',
        ink: '#46332a',
        muted: '#706960',
        border: '#e4e2dd',
        controlBorder: '#8c887f',
        selected: '#e7f4f9',
        primary: '#a8dff1',
        onPrimary: '#244955',
        success: '#3d7335',
        successBg: '#edf5eb',
        warning: '#805c10',
        warningBg: '#fff4d6',
        danger: '#a7364d',
        dangerBg: '#fdeef1',
      };
  const navigation = {
    ground: palette.sidebar,
    ink: palette.ink,
    muted: palette.muted,
    accent: palette.accent,
    selected: palette.selected,
    selectedInk: palette.accent,
    hover: dark ? '#2c3035' : '#eaeae4',
  };
  const config: ThemeConfig = {
    algorithm: dark ? theme.darkAlgorithm : theme.defaultAlgorithm,
    cssVar: { key: 'cinna-fancon' },
    token: {
      colorPrimary: palette.accent,
      colorInfo: palette.accent,
      colorSuccess: palette.success,
      colorWarning: palette.warning,
      colorError: palette.danger,
      colorInfoBg: palette.selected,
      colorInfoBgHover: palette.selected,
      colorInfoText: palette.accent,
      colorSuccessBg: palette.successBg,
      colorSuccessBgHover: palette.successBg,
      colorSuccessText: palette.success,
      colorWarningBg: palette.warningBg,
      colorWarningBgHover: palette.warningBg,
      colorWarningText: palette.warning,
      colorErrorBg: palette.dangerBg,
      colorErrorBgHover: palette.dangerBg,
      colorErrorText: palette.danger,
      colorBgLayout: palette.ground,
      colorBgContainer: palette.surface,
      colorBgElevated: palette.elevated,
      colorText: palette.ink,
      colorTextSecondary: palette.muted,
      colorTextTertiary: palette.muted,
      colorTextDescription: palette.muted,
      colorBorderSecondary: palette.border,
      colorBorder: palette.controlBorder,
      colorPrimaryBg: palette.selected,
      colorPrimaryBgHover: palette.selected,
      colorPrimaryBorder: palette.accent,
      colorPrimaryText: palette.accent,
      colorLink: palette.accent,
      colorLinkHover: palette.accent,
      controlOutline: palette.accent,
      controlHeight: 36,
      controlHeightSM: 32,
      borderRadius: 8,
      borderRadiusLG: 12,
      fontFamily,
      fontSize: 14,
      fontSizeSM: 12,
      motion: !reducedMotion,
      motionDurationFast: '0.12s',
      motionDurationMid: '0.18s',
      boxShadow: 'none',
      boxShadowSecondary: dark ? '0 16px 48px rgba(0,0,0,.4)' : '0 16px 48px rgba(27,37,51,.12)',
    },
    components: {
      Card: { paddingLG: 24, headerFontSize: 16 },
      Button: {
        colorPrimary: palette.primary,
        colorPrimaryHover: dark ? '#c8edf8' : '#bce7f5',
        colorPrimaryActive: '#8bcbe0',
        primaryColor: palette.onPrimary,
        fontWeight: 500,
        primaryShadow: 'none',
        defaultShadow: 'none',
      },
      Menu: {
        itemHeight: 36,
        itemMarginBlock: 4,
        itemMarginInline: 0,
        itemBorderRadius: 8,
        itemBg: 'transparent',
        itemColor: navigation.muted,
        itemSelectedBg: navigation.selected,
        itemSelectedColor: navigation.selectedInk,
        itemHoverBg: navigation.hover,
        itemHoverColor: navigation.ink,
        darkItemBg: 'transparent',
        darkItemColor: navigation.muted,
        darkItemSelectedBg: navigation.selected,
        darkItemSelectedColor: navigation.selectedInk,
        darkItemHoverBg: navigation.hover,
        darkItemHoverColor: navigation.ink,
      },
      Layout: { headerHeight: 40, siderBg: palette.sidebar, triggerBg: palette.sidebar },
      Segmented: { itemSelectedBg: palette.selected, itemSelectedColor: palette.accent },
      Checkbox: { colorWhite: dark ? palette.onPrimary : '#ffffff' },
      Radio: {
        buttonSolidCheckedBg: palette.primary,
        buttonSolidCheckedHoverBg: dark ? '#c8edf8' : '#bce7f5',
        buttonSolidCheckedActiveBg: '#8bcbe0',
        buttonSolidCheckedColor: palette.onPrimary,
        colorWhite: dark ? palette.onPrimary : '#ffffff',
      },
      Switch: { handleBg: dark ? palette.onPrimary : '#ffffff' },
      Select: { optionHeight: 36, optionPadding: '8px 12px' },
      Statistic: { contentFontSize: 40 },
      Table: { cellPaddingBlock: 16 },
    },
  };
  const token = theme.getDesignToken(config);
  return {
    config,
    variables: {
      '--fd-ink': token.colorText,
      '--fd-muted': token.colorTextSecondary,
      '--fd-border': token.colorBorderSecondary,
      '--fd-primary': token.colorPrimary,
      '--fd-focus': palette.accent,
      '--fd-primary-bg': token.colorPrimaryBg,
      '--fd-fill': token.colorFillQuaternary,
      '--fd-container': token.colorBgContainer,
      '--fd-layout': token.colorBgLayout,
      '--fd-control-border': palette.controlBorder,
      '--fd-nav-bg': navigation.ground,
      '--fd-nav-ink': navigation.ink,
      '--fd-nav-muted': navigation.muted,
      '--fd-nav-accent': navigation.accent,
      '--fd-font-family': fontFamily,
      '--fd-selection': palette.primary,
      '--fd-selection-ink': palette.onPrimary,
      '--fd-space-near': '8px',
      '--fd-space-group': '16px',
      '--fd-space-section': '24px',
      '--fd-radius-control': '8px',
      '--fd-radius-panel': '12px',
      '--fd-window-close': '#bc3545',
      '--fd-on-close': '#ffffff',
    },
  };
}
